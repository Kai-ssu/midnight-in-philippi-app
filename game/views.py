import time

import segno
from django.conf import settings
from django.http import Http404
from django.shortcuts import redirect, render
from django.urls import reverse
from django.utils.crypto import constant_time_compare, salted_hmac
from django.utils.safestring import mark_safe
from django.views.decorators.http import require_http_methods, require_POST

from .stages import FINAL_STAGE, FREEDOM_ENTRANCE, GAME_MINUTES, STAGES

# Session keys. "progress" is the highest stage the team may open:
# 0 = not started, 1..FINAL_STAGE = on that stage, FINAL_STAGE + 1 = escaped.
PROGRESS = "progress"
STARTED_AT = "started_at"
FINISHED_AT = "finished_at"
# The page number whose entrance animation is still to be played.
ENTRANCE = "entrance"
# Proof this device entered the leader passcode (tied to the passcode itself).
LEADER = "leader"


def _progress(request):
    return request.session.get(PROGRESS, 0)


def _take_entrance(request, number):
    """True only on the first view of a page the team has just unlocked."""
    return request.session.pop(ENTRANCE, None) == number


def _unlock(request, number):
    request.session[PROGRESS] = number
    request.session[ENTRANCE] = number


def _resume_url(progress):
    if progress < 1:
        return reverse("intro")
    if progress > FINAL_STAGE:
        return reverse("freedom")
    return reverse("stage", args=[progress])


def _timer_context(request):
    started_at = request.session.get(STARTED_AT)
    if started_at is None:
        return {}
    return {"deadline": started_at + GAME_MINUTES * 60}


def landing(request):
    """Home page: choose between playing, leading the game, or reading about it."""
    return render(request, "game/landing.html")


def about(request):
    return render(request, "game/about.html")


def _join_link(request):
    """The player start page's full address, plus a QR code for it as inline SVG."""
    url = request.build_absolute_uri(reverse("intro"))
    qr = segno.make(url, error="m").svg_inline(omitsize=True, border=2, dark="#120d09", light="#f1e3c4")
    return {
        "join_url": url,
        "join_url_short": url.split("://", 1)[-1].rstrip("/"),
        "join_qr": mark_safe(qr),  # generated by segno from our own URL
    }


def facilitator(request):
    """Run-of-show for leaders. Public, so it must never show answers."""
    return render(request, "game/facilitator.html", _join_link(request))


def _leader_token():
    """Changes whenever LEADER_CODE changes, so a new passcode locks every device."""
    return salted_hmac("leader-answer-key", settings.LEADER_CODE).hexdigest()


@require_http_methods(["GET", "POST"])
def answers(request):
    """Answer key for leaders, behind the LEADER_CODE passcode."""
    configured = bool(settings.LEADER_CODE)
    error = None
    if request.method == "POST":
        if request.POST.get("action") == "lock":
            request.session.pop(LEADER, None)
            return redirect("answers")
        if configured and constant_time_compare(request.POST.get("passcode", "").strip(), settings.LEADER_CODE):
            request.session[LEADER] = _leader_token()
            return redirect("answers")
        error = "That passcode isn't right."
    unlocked = configured and constant_time_compare(request.session.get(LEADER, ""), _leader_token())
    return render(
        request,
        "game/answers.html",
        {
            "configured": configured,
            "unlocked": unlocked,
            "error": error,
            "stages": list(STAGES.values()) if unlocked else [],
        },
    )


def intro(request):
    return render(
        request,
        "game/intro.html",
        {
            "progress": _progress(request),
            "resume_url": _resume_url(_progress(request)),
            "game_minutes": GAME_MINUTES,
        },
    )


@require_POST
def start(request):
    if _progress(request) == 0:
        _unlock(request, 1)
        request.session[STARTED_AT] = int(time.time())
    return redirect(_resume_url(_progress(request)))


@require_http_methods(["GET", "POST"])
def stage(request, number):
    current = STAGES.get(number)
    if current is None:
        raise Http404
    progress = _progress(request)
    if number > progress:
        return redirect(_resume_url(progress))

    solved = number < progress
    error = None
    if request.method == "POST":
        if solved:
            return redirect(_resume_url(progress))
        if current.accepts(request.POST.get("code", "")):
            _unlock(request, number + 1)
            if number == FINAL_STAGE:
                request.session[FINISHED_AT] = int(time.time())
            return redirect(_resume_url(number + 1))
        error = "The lock doesn't budge. Check the Scriptures and try again."

    return render(
        request,
        "game/stage.html",
        {
            "stage": current,
            "solved": solved,
            "error": error,
            "reached": [STAGES[n] for n in STAGES if n <= progress],
            "next_url": _resume_url(number + 1) if solved else None,
            "entrance": current.entrance if _take_entrance(request, number) else None,
            **_timer_context(request),
        },
    )


def freedom(request):
    if _progress(request) <= FINAL_STAGE:
        return redirect(_resume_url(_progress(request)))
    elapsed = request.session.get(FINISHED_AT, 0) - request.session.get(STARTED_AT, 0)
    minutes, seconds = divmod(max(elapsed, 0), 60)
    return render(
        request,
        "game/freedom.html",
        {
            "elapsed": f"{minutes}:{seconds:02d}",
            "reached": [STAGES[n] for n in STAGES],
            "entrance": FREEDOM_ENTRANCE if _take_entrance(request, FINAL_STAGE + 1) else None,
        },
    )


def backdrop(request):
    """Full-screen projector display with the room countdown. No game state."""
    return render(request, "game/backdrop.html", _join_link(request))


def debrief(request):
    """Projector slides with the debrief discussion questions."""
    return render(request, "game/debrief.html")


@require_http_methods(["GET", "POST"])
def reset(request):
    """For the Gamemaster: wipe this device's progress between groups."""
    if request.method == "POST":
        request.session.flush()
        return redirect("intro")
    return render(request, "game/reset.html")
